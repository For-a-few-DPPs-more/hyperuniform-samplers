def optimize_points(quad, N=50, steps=200, lr=0.1):

    device = quad.device
    B = quad.shape[0]

    # target distribution = vrai quad
    target = sample_quad(quad, N)

    # init points dans bounding box
    minb = quad.min(dim=1, keepdim=True).values
    maxb = quad.max(dim=1, keepdim=True).values

    x = torch.rand(B, N, 2, device=device)
    x = minb + x * (maxb - minb)

    x.requires_grad_(True)

    opt = torch.optim.Adam([x], lr=lr)

    for i in range(steps):
        opt.zero_grad()

        loss = sinkhorn(x, target)

        loss.backward()
        opt.step()

        if i % 20 == 0:
            print(f"step {i} | loss = {loss.item():.6f}")

    return x.detach()

