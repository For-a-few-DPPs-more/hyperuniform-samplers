import numpy as np


# ------------------------------------------------------------
# Aire spécialisée quadrilatère
# ------------------------------------------------------------

def quad_signed_area(q):
    x0, y0 = q[..., 0, 0], q[..., 0, 1]
    x1, y1 = q[..., 1, 0], q[..., 1, 1]
    x2, y2 = q[..., 2, 0], q[..., 2, 1]
    x3, y3 = q[..., 3, 0], q[..., 3, 1]

    return 0.5 * (
        x0 * y1 - x1 * y0
        + x1 * y2 - x2 * y1
        + x2 * y3 - x3 * y2
        + x3 * y0 - x0 * y3
    )


def area4(P0, P1, P2, P3):
    return 0.5 * (
        P0[..., 0] * P1[..., 1] - P1[..., 0] * P0[..., 1]
        + P1[..., 0] * P2[..., 1] - P2[..., 0] * P1[..., 1]
        + P2[..., 0] * P3[..., 1] - P3[..., 0] * P2[..., 1]
        + P3[..., 0] * P0[..., 1] - P0[..., 0] * P3[..., 1]
    )


