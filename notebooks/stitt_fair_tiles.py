# ============================================================
# Triangle moments
# ============================================================

def triangle_moments(v0, v1, v2, P, nq=8):
    """
    Moments géométriques exacts (à précision quadrature)
    d'un triangle.

    Retour:
        dict[(i,j)] -> (B,)
    """

    B = v0.shape[0]

    # Gauss-Legendre sur [0,1]
    xg, wg = jnp.polynomial.legendre.leggauss(nq)

    u = 0.5 * (xg + 1.0)
    wu = 0.5 * wg

    uu, vv = jnp.meshgrid(u, u, indexing="ij")
    wu2, wv2 = jnp.meshgrid(wu, wu, indexing="ij")

    uu = uu.reshape(-1)
    vv = vv.reshape(-1)

    weights = (wu2 * wv2).reshape(-1)

    # transformation carré -> triangle
    r = uu
    s = (1.0 - uu) * vv

    jac_ref = (1.0 - uu)

    p = (
        v0[:, None, :]
        + r[None, :, None] * (v1 - v0)[:, None, :]
        + s[None, :, None] * (v2 - v0)[:, None, :]
    )

    x = p[..., 0]
    y = p[..., 1]

    J = jnp.abs(
        (v1[:, 0] - v0[:, 0]) * (v2[:, 1] - v0[:, 1])
        - (v1[:, 1] - v0[:, 1]) * (v2[:, 0] - v0[:, 0])
    )

    det = J[:, None] * jac_ref[None, :]

    moments = {}

    for order in range(P + 1):
        for i in range(order + 1):
            j = order - i

            val = jnp.sum(
                weights[None, :]
                * det
                * (x ** i)
                * (y ** j),
                axis=1,
            )

            moments[(i, j)] = val

    return moments


# ============================================================
# Quad moments
# ============================================================

def quad_moments(quad, P):
    """
    quad : (B,4,2)
    """

    q0 = quad[:, 0]
    q1 = quad[:, 1]
    q2 = quad[:, 2]
    q3 = quad[:, 3]

    m1 = triangle_moments(q0, q1, q2, P)
    m2 = triangle_moments(q0, q2, q3, P)

    return {
        k: m1[k] + m2[k]
        for k in m1
    }


# ============================================================
# Bilinear mapping square -> quad
# ============================================================

def bilinear_map(quad, uv):
    """
    quad : (B,4,2)
    uv   : (B,N,2)
    """

    u = uv[..., 0:1]
    v = uv[..., 1:2]

    q0 = quad[:, None, 0]
    q1 = quad[:, None, 1]
    q2 = quad[:, None, 2]
    q3 = quad[:, None, 3]

    return (
        (1-u)*(1-v)*q0
        + u*(1-v)*q1
        + u*v*q2
        + (1-u)*v*q3
    )


