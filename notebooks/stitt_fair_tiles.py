# Sampler
# ============================================================

def sample_as_jax(
    quad,
    N,
    P,
    max_iter=200,
):
    B = quad.shape[0]

    target = quad_moments(quad, P)

    area = target[(0, 0)]

    key = jax.random.PRNGKey(0)

    uv0 = jax.random.uniform(
        key,
        (B, N, 2),
        minval=0.05,
        maxval=0.95,
    )

    def loss_fn(z):

        uv = jax.nn.sigmoid(z)

        pts = bilinear_map(quad, uv)

        x = pts[..., 0]
        y = pts[..., 1]

        loss = 0.0

        for order in range(P + 1):
            for i in range(order + 1):
                j = order - i

                discrete = (
                    area / N
                    * jnp.sum(
                        x**i * y**j,
                        axis=1,
                    )
                )

                tgt = target[(i, j)]

                rel = (
                    (discrete - tgt)
                    / (jnp.abs(tgt) + 1e-12)
                )

                loss += jnp.mean(rel**2)

        return loss

    z0 = jnp.log(uv0) - jnp.log1p(-uv0)

    solver = LBFGS(
        fun=loss_fn,
        maxiter=max_iter,
        tol=1e-10,
    )

    res = solver.run(z0)

    uv = jax.nn.sigmoid(res.params)

    return bilinear_map(quad, uv)

