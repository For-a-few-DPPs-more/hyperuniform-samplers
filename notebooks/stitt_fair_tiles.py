import torch

def sample_quad(quad, N):
    """
    quad: (B,4,2)
    return: (B,N,2)
    """

    B = quad.shape[0]
    u = torch.rand(B, N, 2, device=quad.device)

    q0, q1, q2, q3 = quad[:,0], quad[:,1], quad[:,2], quad[:,3]

    pts = (
        (1-u[...,0:1])*(1-u[...,1:2])*q0[:,None]
        + u[...,0:1]*(1-u[...,1:2])*q1[:,None]
        + u[...,0:1]*u[...,1:2]*q2[:,None]
        + (1-u[...,0:1])*u[...,1:2]*q3[:,None]
    )

    return pts

